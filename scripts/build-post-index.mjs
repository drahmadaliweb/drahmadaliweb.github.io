import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import topicTaxonomy from '../topic-taxonomy.mjs';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const postsDir = path.join(root, 'posts');
const output = path.join(root, 'posts-manifest.js');

const names = (await fs.readdir(postsDir))
  .filter(name => name.endsWith('.mjs') && !name.startsWith('_'))
  .sort();

const posts = [];
const ids = new Set();

for (const name of names) {
  const filePath = path.join(postsDir, name);
  const mod = await import(`${pathToFileURL(filePath).href}?v=${Date.now()}-${encodeURIComponent(name)}`);
  const post = structuredClone(mod.default);
  const id = post.id || name.replace(/\.mjs$/i, '');

  if (ids.has(id)) throw new Error(`Duplicate post id: ${id}`);
  ids.add(id);

  if (!post.date || !/^\d{4}-\d{2}-\d{2}$/.test(post.date)) {
    throw new Error(`${name}: date must use YYYY-MM-DD.`);
  }
  if (!post.bn?.title || !post.bn?.body) {
    throw new Error(`${name}: Bengali title/body are required.`);
  }
  if (!post.topic_slug || !topicTaxonomy[post.topic_slug]) {
    throw new Error(`${name}: topic_slug must be one of the canonical topic slugs.`);
  }
  delete post.topic;
  if (!post.en?.title || !post.en?.body) {
    throw new Error(`${name}: English title/body are required.`);
  }

  post.id = id;
  posts.push(post);
}

posts.sort((a,b) => String(b.date).localeCompare(String(a.date)) || a.id.localeCompare(b.id));

const banner = `/* AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY.\n   Add/edit files in /posts instead.\n   Generated by scripts/build-post-index.mjs. */\n`;
const js = `${banner}window.windowOfTimePosts = ${JSON.stringify(posts, null, 2)};\n`;
await fs.writeFile(output, js, 'utf8');
console.log(`Built ${path.relative(root, output)} from ${posts.length} post(s).`);
