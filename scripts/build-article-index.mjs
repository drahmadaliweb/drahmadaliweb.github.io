import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import topicTaxonomy from '../topic-taxonomy.mjs';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'articles');
const output = path.join(root, 'selected-articles-manifest.js');
const names = (await fs.readdir(dir)).filter(n => n.endsWith('.mjs') && !n.startsWith('_')).sort();
const items=[]; const ids=new Set();
for (const name of names) {
  const mod=await import(`${pathToFileURL(path.join(dir,name)).href}?v=${Date.now()}-${encodeURIComponent(name)}`);
  const item=structuredClone(mod.default);
  const id=item.id || name.replace(/\.mjs$/i,'');
  if(ids.has(id)) throw new Error(`Duplicate article id: ${id}`); ids.add(id);
  if(!item.date || !/^\d{4}-\d{2}-\d{2}$/.test(item.date)) throw new Error(`${name}: date must use YYYY-MM-DD.`);
  if(!item.bn?.title || !item.en?.title) throw new Error(`${name}: Bengali and English titles are required.`);
  if(!item.topic_slug || !topicTaxonomy[item.topic_slug]) throw new Error(`${name}: topic_slug must be one of the canonical topic slugs.`);
  delete item.topic;
  item.id=id; items.push(item);
}
items.sort((a,b)=>String(b.date).localeCompare(String(a.date)) || a.id.localeCompare(b.id));
const banner=`/* AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY.
   Add/edit files in /articles instead.
   Generated by scripts/build-article-index.mjs. */
`;
await fs.writeFile(output, `${banner}window.ahmadAliSelectedArticles = ${JSON.stringify(items,null,2)};
`, 'utf8');
console.log(`Built ${path.relative(root,output)} from ${items.length} article(s).`);
