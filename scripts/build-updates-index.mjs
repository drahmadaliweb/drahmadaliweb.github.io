import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const updatesDir = path.join(root, 'updates');
const output = path.join(root, 'updates-manifest.js');

const names = (await fs.readdir(updatesDir))
  .filter(name => name.endsWith('.mjs') && !name.startsWith('_'))
  .sort();

const updates = [];
const ids = new Set();
for (const name of names) {
  const filePath = path.join(updatesDir, name);
  const mod = await import(`${pathToFileURL(filePath).href}?v=${Date.now()}-${encodeURIComponent(name)}`);
  const item = structuredClone(mod.default || {});
  const id = item.id || name.replace(/\.mjs$/i, '');
  if (ids.has(id)) throw new Error(`Duplicate update id: ${id}`);
  ids.add(id);
  if (!item.date || !/^\d{4}-\d{2}-\d{2}$/.test(item.date)) throw new Error(`${name}: date must use YYYY-MM-DD.`);
  if (!item.en?.title || !item.bn?.title) throw new Error(`${name}: English and Bengali titles are required.`);
  item.id = id;
  item.href = item.href || '';
  updates.push(item);
}

updates.sort((a,b) => String(b.date).localeCompare(String(a.date)) || a.id.localeCompare(b.id));
const banner = `/* AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY.
   Add/edit files in /updates instead.
   Generated by scripts/build-updates-index.mjs. */
`;
await fs.writeFile(output, `${banner}window.ahmadAliUpdates = ${JSON.stringify(updates, null, 2)};
`, 'utf8');
console.log(`Built ${path.relative(root, output)} from ${updates.length} update(s).`);
