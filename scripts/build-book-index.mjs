import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const dir = path.join(root, 'books');
const files = (await readdir(dir)).filter(f => f.endsWith('.mjs') && !f.startsWith('_')).sort();
const items=[];
for (const file of files) {
  const mod = await import(`${pathToFileURL(path.join(dir,file)).href}?v=${Date.now()}`);
  const book = mod.default;
  if (!book || !book.id || !book.bn?.title) throw new Error(`Invalid book file: ${file}`);
  items.push(book);
}
const banglaCollator = new Intl.Collator('bn-BD', { sensitivity: 'base', numeric: true, ignorePunctuation: true });
items.sort((a,b) => banglaCollator.compare(
  String(a?.bn?.title || a?.en?.originalTitle || a?.en?.title || '').trim(),
  String(b?.bn?.title || b?.en?.originalTitle || b?.en?.title || '').trim()
));
const out = `/* AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY.\n   Add/edit files in /books instead.\n   Generated by scripts/build-book-index.mjs. */\nwindow.ahmadAliBookDetails = ${JSON.stringify(items,null,2)};\n`;
await writeFile(path.join(root,'books-manifest.js'),out,'utf8');
console.log(`Built books-manifest.js with ${items.length} detailed books.`);
