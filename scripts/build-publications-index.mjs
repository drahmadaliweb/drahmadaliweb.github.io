import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const root=path.resolve(path.dirname(new URL(import.meta.url).pathname),'..');
const dir=path.join(root,'publications');
const output=path.join(root,'publications-manifest.js');
const names=(await fs.readdir(dir)).filter(n=>n.endsWith('.mjs')&&!n.startsWith('_')).sort();
const items=[]; const ids=new Set();
for(const name of names){
  const mod=await import(`${pathToFileURL(path.join(dir,name)).href}?v=${Date.now()}-${encodeURIComponent(name)}`);
  const item=structuredClone(mod.default||{}); const id=item.id||name.replace(/\.mjs$/i,'');
  if(ids.has(id)) throw new Error(`Duplicate publication id: ${id}`); ids.add(id);
  if(!item.type) throw new Error(`${name}: type is required.`);
  if(!item.titleEn&&!item.titleBn&&!item.titleAr) throw new Error(`${name}: at least one title is required.`);
  item.id=id; items.push(item);
}
items.sort((a,b)=>(Number(a.order||9999)-Number(b.order||9999))||String(a.id).localeCompare(String(b.id)));
const banner=`/* AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY.\n   Add/edit files in /publications instead.\n   Generated by scripts/build-publications-index.mjs. */\n`;
await fs.writeFile(output,`${banner}window.ahmadAliPublications = ${JSON.stringify(items,null,2)};\n`,'utf8');
console.log(`Built ${path.relative(root,output)} from ${items.length} publication(s).`);
